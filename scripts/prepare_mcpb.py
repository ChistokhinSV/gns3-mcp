#!/usr/bin/env python3
"""Prepare mcp-server/ for `mcpb pack` (MCPB manifest 0.4, uv server type).

Claude Desktop installs the bundle's dependencies with its own uv from
`mcp-server/pyproject.toml`, so the bundle carries only source code:

- copies gns3_mcp/ into mcp-server/gns3_mcp/ (without caches)
- writes mcp-server/pyproject.toml from the root pyproject (same version and
  runtime dependencies), so the two cannot drift

Used by `just build` and the release workflow. Run from the repository root.
"""

import shutil
import sys
from pathlib import Path

import tomllib

ROOT = Path(__file__).resolve().parent.parent
BUNDLE_DIR = ROOT / "mcp-server"


def bundle_pyproject(root_pyproject: dict) -> str:
    """Render the bundle's pyproject.toml from the root project table"""
    project = root_pyproject["project"]
    deps = "\n".join(f'    "{dep}",' for dep in project["dependencies"])
    return (
        "# Generated by scripts/prepare_mcpb.py - do not edit, change the root pyproject.toml\n"
        "[project]\n"
        'name = "gns3-mcp-bundle"\n'
        f'version = "{project["version"]}"\n'
        f'requires-python = "{project["requires-python"]}"\n'
        f"dependencies = [\n{deps}\n]\n"
        "\n"
        "# Dependencies only: the source runs from this folder, nothing is built\n"
        "[tool.uv]\n"
        "package = false\n"
    )


def main() -> int:
    with open(ROOT / "pyproject.toml", "rb") as f:
        root_pyproject = tomllib.load(f)

    target = BUNDLE_DIR / "gns3_mcp"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(
        ROOT / "gns3_mcp",
        target,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )

    (BUNDLE_DIR / "pyproject.toml").write_text(bundle_pyproject(root_pyproject), encoding="utf-8")

    version = root_pyproject["project"]["version"]
    print(f"Prepared mcp-server/ for MCPB {version} (uv runtime, source only)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
