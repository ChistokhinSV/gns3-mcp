#!/usr/bin/env python3
"""Render plugin/assets/icon.svg to the images the packages and the repo use.

- plugin/assets/icon.png            1024 px   (Claude plugin, `icon` in plugin.json;
                                               the directory needs 512-2048 px)
- mcp-server/icon.png                512 px   (MCPB `icon`, 512 px recommended by the spec)
- docs/assets/social-preview.svg/png 1280x640 (GitHub social preview: icon + name + tagline;
                                               upload by hand under Settings > General)

The outputs are committed (the plugin is installed straight from git), so run this after
editing the icon. Run from the repository root; needs cairosvg (a runtime dependency) and
Pillow (only to measure text for the social preview pills).
"""

import re
import sys
from pathlib import Path

import cairosvg

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "plugin" / "assets" / "icon.svg"
TARGETS = {
    ROOT / "plugin" / "assets" / "icon.png": 1024,
    ROOT / "mcp-server" / "icon.png": 512,
}
SOCIAL_SVG = ROOT / "docs" / "assets" / "social-preview.svg"
SOCIAL_PNG = ROOT / "docs" / "assets" / "social-preview.png"

FONT = "Segoe UI, Helvetica Neue, Arial, sans-serif"
# Used only to measure pill widths; any sans font gives close enough numbers
MEASURE_FONT = Path("C:/Windows/Fonts/seguisb.ttf")

TITLE = "GNS3 MCP"
TAGLINE = ["Network lab automation", "for Claude and MCP clients"]
DETAILS = "Nodes · links · consoles · SSH · topology export"
PILLS = ["Claude plugin", "MCP server", "PyPI", "Docker"]

# Faint graph behind the text, echoing the icon (tile coordinates of the 1280x640 card)
BG_NODES = [
    (700, 70),
    (860, 40),
    (1020, 96),
    (1190, 60),
    (1240, 230),
    (1240, 600),
    (960, 610),
    (760, 590),
]
BG_EDGES = [(0, 1), (1, 2), (2, 3), (3, 4), (2, 4), (5, 6), (6, 7), (4, 5)]


def text_width(text: str, size: int) -> float:
    try:
        from PIL import ImageFont

        return ImageFont.truetype(str(MEASURE_FONT), size).getlength(text)
    except (ImportError, OSError):
        return len(text) * size * 0.56


def social_svg(icon_svg: str) -> str:
    """1280x640 card: icon tile left, name, tagline, details and pills right"""
    # Nest the icon as an inline <svg> (cairosvg does not load SVGs through <image>)
    icon = re.sub(
        r"<svg [^>]*>",
        '<svg x="96" y="112" width="416" height="416" viewBox="0 0 512 512">',
        icon_svg,
        count=1,
    )

    pills, x = [], 580
    for label in PILLS:
        w = text_width(label, 26) + 40
        pills.append(
            f'<rect x="{x:.0f}" y="478" width="{w:.0f}" height="48" rx="24" fill="#0f4a45" stroke="#32b29d" stroke-width="2"/>'
            f'<text x="{x + w / 2:.0f}" y="511" text-anchor="middle" font-size="26" font-weight="600" fill="#bdf2dd">{label}</text>'
        )
        x += w + 14

    edges = "".join(
        f'<line x1="{BG_NODES[a][0]}" y1="{BG_NODES[a][1]}" x2="{BG_NODES[b][0]}" y2="{BG_NODES[b][1]}"/>'
        for a, b in BG_EDGES
    )
    nodes = "".join(f'<circle cx="{nx}" cy="{ny}" r="10"/>' for nx, ny in BG_NODES)

    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 640" width="1280" height="640">
  <!-- Generated by scripts/render_icon.py from plugin/assets/icon.svg - edit the script, not this file -->
  <defs>
    <linearGradient id="card" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#05171d"/>
      <stop offset="1" stop-color="#0b3532"/>
    </linearGradient>
  </defs>
  <rect width="1280" height="640" fill="url(#card)"/>
  <g stroke="#32b29d" stroke-width="4" opacity="0.18">{edges}</g>
  <g fill="#32b29d" opacity="0.22">{nodes}</g>

  <rect x="90" y="106" width="428" height="428" rx="98" fill="none" stroke="#32b29d" stroke-opacity="0.45" stroke-width="3"/>
  {icon}

  <g font-family="{FONT}">
    <text x="576" y="246" font-size="108" font-weight="700" fill="#ffffff">{TITLE}</text>
    <text x="580" y="318" font-size="40" font-weight="600" fill="#c6f86e">{TAGLINE[0]}</text>
    <text x="580" y="368" font-size="40" font-weight="600" fill="#c6f86e">{TAGLINE[1]}</text>
    <text x="580" y="432" font-size="28" fill="#8fd3c0">{DETAILS}</text>
    {"".join(pills)}
  </g>
</svg>
"""


def main() -> int:
    svg = SOURCE.read_bytes()
    for target, size in TARGETS.items():
        cairosvg.svg2png(
            bytestring=svg, write_to=str(target), output_width=size, output_height=size
        )
        print(f"{target.relative_to(ROOT)}: {size}x{size}, {target.stat().st_size // 1024} KB")

    SOCIAL_SVG.parent.mkdir(parents=True, exist_ok=True)
    SOCIAL_SVG.write_text(social_svg(svg.decode("utf-8")), encoding="utf-8")
    cairosvg.svg2png(
        url=str(SOCIAL_SVG), write_to=str(SOCIAL_PNG), output_width=1280, output_height=640
    )
    print(f"{SOCIAL_PNG.relative_to(ROOT)}: 1280x640, {SOCIAL_PNG.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
